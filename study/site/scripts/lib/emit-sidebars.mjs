// Emits sidebars.generated.js — the runtime-loaded sibling of sidebars.js.
//
// components: one collapsible group per component, with sub-items for each
//             feature page. Component index page is the group's link.
// views: flat list of view pages.
// classes: DELIBERATELY EMPTY. A 2,748-item alphabetized sidebar forces
//   Docusaurus to render every entry into the DOM up front, which makes the
//   sidebar sluggish to open, scroll, and expand. Class pages are reached
//   via the search box, feature-page class tables, backlinks, and the
//   reading-order guide — the sidebar is not on that path. sidebars.js
//   silently skips an empty `classes` array, so the "Classes (A–Z)" group
//   just does not appear.

import fs from 'node:fs/promises';
import {sidebarsGeneratedPath} from './paths.mjs';
import {info} from './log.mjs';

function slugifyComponent(comp) {
  return comp.toLowerCase().replace(/[^a-z0-9]+/g, '-');
}

/**
 * @param {{
 *   byComponent: Map<string, Map<string, any[]>>,
 *   resolvedViews: {id: string, title: string}[],
 *   rows: any[],
 *   slugByFqcn: Map<string, string>,
 * }} args
 */
export async function emitSidebars({byComponent, resolvedViews, rows, slugByFqcn}) {
  // Doc ids are the file path relative to docs/ (without extension). That's
  // what Docusaurus uses when the front-matter doesn't set `id:` — which is
  // the case for every page emitted by the atlas pipeline.
  const components = [];
  for (const [comp, feats] of [...byComponent.entries()].sort()) {
    const compSlug = slugifyComponent(comp);
    components.push({
      type: 'category',
      label: comp,
      collapsed: true,
      link: {type: 'doc', id: `component/${compSlug}/index`},
      items: [...feats.keys()].sort().map((feature) => ({
        type: 'doc',
        id: `component/${compSlug}/${feature}`,
        label: feature,
      })),
    });
  }

  const views = resolvedViews.map((v) => ({type: 'doc', id: `view/${v.id}`, label: v.title}));

  // `rows` and `slugByFqcn` are intentionally unused here: the classes list
  // is omitted from the sidebar (see file header). They stay in the argument
  // shape so callers do not have to change.
  void rows;
  void slugByFqcn;

  const body =
    '// Auto-generated by scripts/build-atlas.mjs. Do not hand-edit.\n' +
    'module.exports = ' +
    JSON.stringify({components, views, classes: []}, null, 2) +
    ';\n';
  await fs.writeFile(sidebarsGeneratedPath, body);
  info(
    `emit sidebars.generated.js (${components.length} components, ${views.length} views, classes list intentionally omitted)`,
  );
}
