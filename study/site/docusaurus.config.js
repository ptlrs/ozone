// @ts-check
// Docusaurus 3 configuration for the Ozone Class Study Atlas site.
// This file is intentionally small; heavier logic lives under scripts/.

const path = require('path');
const fs = require('fs');

const themes = require('prism-react-renderer').themes;

/** Load the user's local config, or fall back to a github-mode default. */
function loadLocalConfig() {
  const localPath = path.join(__dirname, 'config.local.js');
  if (fs.existsSync(localPath)) {
    // eslint-disable-next-line global-require, import/no-dynamic-require
    return {config: require(localPath), missing: false};
  }
  return {
    config: {
      repoRoot: '',
      githubRepo: 'apache/ozone',
      githubRef: 'master',
      jetbrainsProject: 'ozone',
      defaultMode: 'github',
    },
    missing: true,
  };
}

const {config: local, missing: localMissing} = loadLocalConfig();

/** Write the runtime config bootstrap that populates window.__ATLAS_CONFIG. */
(function emitRuntimeConfig() {
  const dst = path.join(__dirname, 'static', 'atlas-config.js');
  const body =
    '// Auto-generated by docusaurus.config.js. Do not hand-edit.\n' +
    'window.__ATLAS_CONFIG = ' +
    JSON.stringify({...local, localMissing}, null, 2) +
    ';\n';
  fs.mkdirSync(path.dirname(dst), {recursive: true});
  fs.writeFileSync(dst, body);
})();

